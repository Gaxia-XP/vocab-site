"""Build common.js: everyday English words for the game mode.

Source: wordfreq (word frequency from Wikipedia, subtitles, news, books, web, Reddit, Twitter).
Keep a word if it is in words.js and its Zipf frequency >= MIN_ZIPF,
plus anything in EXTRA_WORDS (words confirmed to work in Finish The Word!).
Output is sorted most-common first: window.COMMON = {words:[...], zipf:[...] (x10)}.

Run: pip install wordfreq && python3 tools/build_common.py
"""
import json, os, re
from wordfreq import iter_wordlist, zipf_frequency

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MIN_ZIPF = 1.5

# Words confirmed accepted by the game; always included (top tier).
EXTRA_WORDS = """
scient xerox xenon food rabbits xci suspect sex sax ill eel nix tsunami xenophobic
xenophobia xenophone electronicity electric galax gist gis git github sandbox saltbox
earwax efflux titans systems
""".split()

src = open(os.path.join(ROOT, 'words.js')).read()
all_words = set(json.loads(src[src.index('['):src.rindex(']') + 1]))

out = {}
for w in iter_wordlist('en', 'large'):
    if not re.fullmatch(r'[a-z]{2,}', w) or w not in all_words:
        continue
    z = zipf_frequency(w, 'en')
    if z < MIN_ZIPF:
        break  # list is ordered by frequency
    out[w] = z
for w in EXTRA_WORDS:
    out[w] = max(out.get(w, 0), 3.0)

ranked = sorted(out, key=lambda w: (-out[w], w))
with open(os.path.join(ROOT, 'common.js'), 'w') as f:
    f.write('// Everyday English words (generated by tools/build_common.py). Most common first.\n')
    f.write('window.COMMON = {"words":' + json.dumps(ranked, separators=(',', ':')))
    f.write(',\n"zipf":' + json.dumps([round(out[w] * 10) for w in ranked], separators=(',', ':')) + '};\n')
print(len(ranked), 'words written to common.js')
